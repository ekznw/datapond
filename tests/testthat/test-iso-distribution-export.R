test_that("URL-only licence identity and nameless MIME resources retain facts without invented titles", {
  core_validation_engine()
  fixture <- iso_export_candidate_pond("vector")
  on.exit(unlink(fixture$path, recursive = TRUE), add = TRUE)
  conn <- datapond:::get_conn(fixture$path)
  on.exit(DBI::dbDisconnect(conn), add = TRUE)
  DBI::dbExecute(conn, "INSERT INTO dataset_license_tbl(dataset_id, license_url) VALUES (?, 'https://example.test/terms')",
                 params = list(fixture$dataset_id))
  datapond:::replace_dataset_online_resources(fixture$dataset_id, data.frame(
    resource_url = "https://example.test/data.csv", function_code = "download", media_type = "text/csv"), fixture$path)
  result <- datapond:::assess_iso_metadata_export(fixture$dataset_id, fixture$path, sections = "distribution")
  expect_true(result$validation$valid, info = paste(result$validation$issues$message, collapse = "\n"))
  ns <- xml2::xml_ns(result$document)
  expect_identical(xml2::xml_attr(xml2::xml_find_first(result$document, "//mco:reference//cit:title", ns), "gco:nilReason", ns), "missing")
  expect_identical(core_xpath_text(result$document, "//mco:reference//cit:linkage/*"), "https://example.test/terms")
  expect_identical(core_xpath_text(result$document, "//mrd:onLine//cit:name/*"), "text/csv")
  DBI::dbExecute(conn, "UPDATE dataset_online_resource_tbl SET resource_url = 'relative/path.csv'")
  result <- datapond:::assess_iso_metadata_export(fixture$dataset_id, fixture$path, sections = "distribution")
  expect_identical(result$validation$status, "not-built")
  expect_match(result$validation$issues$message, "absolute URI")
})
