test_that("distribution, licensing and core lineage validate together using stored values", {
  core_validation_engine()
  for (kind in c("vector", "raster")) {
    fixture <- distribution_fixture(kind)
    result <- datapond:::assess_iso_metadata_export(fixture$dataset_id, fixture$path, sections = "distribution")
    expect_identical(result$validation$status, "pass", info = paste(result$validation$issues$message, collapse = "\n"))
    expect_identical(result$export_scope, "distribution")
    expect_match(result$validation$coverage, "Excludes quality", fixed = TRUE)
    xml <- result$document
    ns <- xml2::xml_ns(xml)
    conn <- datapond:::get_conn(fixture$path)
    formats <- DBI::dbGetQuery(conn, "SELECT * FROM dataset_distribution_format_tbl ORDER BY sort_order")
    online <- DBI::dbGetQuery(conn, "SELECT * FROM dataset_online_resource_tbl ORDER BY sort_order")
    rights <- DBI::dbGetQuery(conn, "SELECT * FROM dataset_license_tbl")
    expect_identical(core_xpath_text(xml, "//mrd:formatSpecificationCitation//cit:title/*"), formats$specification_title)
    expect_identical(xml2::xml_attr(xml2::xml_find_all(xml, "//mrd:formatSpecificationCitation//gcx:MimeFileType", ns), "type"), formats$media_type)
    expect_identical(core_xpath_text(xml, "//mrd:formatSpecificationCitation//cit:edition/*"), "1.3")
    expect_identical(core_xpath_text(xml, "//mrd:formatSpecificationCitation//cit:linkage/*"), formats$format_uri[!is.na(formats$format_uri)])
    expect_length(xml2::xml_find_all(xml, "//mrd:medium", ns), 0L)
    expect_identical(core_xpath_text(xml, "//mrd:onLine//cit:linkage/*"), online$resource_url)
    expect_identical(core_xpath_text(xml, "//mrd:onLine//cit:name/*"), online$resource_name)
    expect_identical(core_xpath_text(xml, "//mrd:onLine//cit:description/*"), online$resource_description)
    expect_identical(core_xpath_text(xml, "//mrd:onLine//cit:protocol/*"), online$protocol)
    expect_identical(core_xpath_text(xml, "//mrd:onLine//cit:CI_OnLineFunctionCode"), online$function_code)
    expect_identical(xml2::xml_attr(xml2::xml_find_all(xml, "//mrd:onLine//gcx:MimeFileType", ns), "type"), online$media_type)
    expect_length(xml2::xml_find_all(xml, "//mrd:MD_Distributor", ns), 1L)
    expect_identical(core_xpath_text(xml, "//mco:reference//cit:title/*"), rights$license_name)
    expect_identical(core_xpath_text(xml, "//mco:reference//mcc:code/*"), rights$license_identifier)
    expect_identical(core_xpath_text(xml, "//mco:reference//cit:linkage/*"), rights$license_url)
    expect_identical(core_xpath_text(xml, "//mco:responsibleParty//cit:name/*"), "Fixture Metadata Office")
    expect_identical(core_xpath_text(xml, "//mco:useLimitation/*"), c(rights$use_constraints, rights$attribution_text))
    expect_identical(core_xpath_text(xml, "//mco:MD_LegalConstraints/mco:releasability/mco:MD_Releasability/mco:statement/*"), rights$release_statement)
    other <- core_xpath_text(xml, "//mco:otherConstraints/*")
    expect_true(all(c(rights$license_description, rights$permission_reference, rights$sensitivity_reason,
      "Request exact site locations from the custodian.", "Embargo end: 2027-01-31") %in% other))
    expect_false(grepl("PRIVATE INTERNAL NOTE|Obsolete licence snapshot|Stale holder snapshot", as.character(xml)))
    expect_length(xml2::xml_find_all(xml, "//mrl:LI_Lineage", ns), 1L)
    expect_identical(as.character(datapond:::build_iso_distribution_metadata_xml(fixture$dataset_id, fixture$path)), as.character(xml))
    DBI::dbDisconnect(conn)
    unlink(fixture$path, recursive = TRUE)
  }
})

test_that("supplementary constraints are additive and conservative whitespace duplicates are removed", {
  fixture <- distribution_fixture()
  on.exit(unlink(fixture$path, recursive = TRUE), add = TRUE)
  conn <- datapond:::get_conn(fixture$path)
  on.exit(DBI::dbDisconnect(conn), add = TRUE)
  DBI::dbExecute(conn, "UPDATE entry_tbl SET use_limitations = '  Not suitable   for navigation. ', access_constraints = ' Credit  the source. '")
  xml <- datapond:::build_iso_distribution_metadata_xml(fixture$dataset_id, fixture$path)
  expect_identical(core_xpath_text(xml, "//mco:useLimitation/*"), c("Not suitable for navigation.", "Survey team (2026)."))
  expect_equal(sum(core_xpath_text(xml, "//mco:otherConstraints/*") == "Credit the source."), 1L)
  DBI::dbExecute(conn, "UPDATE entry_tbl SET use_limitations = 'Not suitable for navigation without local checks.', access_constraints = 'Credit the Source.'")
  xml <- datapond:::build_iso_distribution_metadata_xml(fixture$dataset_id, fixture$path)
  expect_true("Not suitable for navigation without local checks." %in% core_xpath_text(xml, "//mco:useLimitation/*"))
  expect_true(all(c("Credit the source.", "Credit the Source.") %in% core_xpath_text(xml, "//mco:otherConstraints/*")))
  expect_identical(DBI::dbGetQuery(conn, "SELECT use_limitations FROM entry_tbl")$use_limitations,
                   "Not suitable for navigation without local checks.")
})

test_that("licence fallback works without a licence and with an embargo-only row", {
  core_validation_engine()
  fixture <- iso_export_candidate_pond("vector")
  on.exit(unlink(fixture$path, recursive = TRUE), add = TRUE)
  conn <- datapond:::get_conn(fixture$path)
  on.exit(DBI::dbDisconnect(conn), add = TRUE)
  datapond:::ensure_columns(conn, "entry_tbl", c("access_constraints", "use_limitations", "license_type"))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET license_type = 'Provider terms', access_constraints = 'Ask provider.', use_limitations = 'Planning use only.'")
  for (embargo in c(FALSE, TRUE)) {
    if (embargo) datapond:::save_dataset_release_rights(fixture$dataset_id,
      list(embargo_status = "Yes", embargo_reason = "Under review", embargo_end_date = "2027-01-01"), fixture$path)
    result <- datapond:::assess_iso_metadata_export(fixture$dataset_id, fixture$path, sections = "distribution")
    expect_true(result$validation$valid, info = paste(result$validation$issues$message, collapse = "\n"))
    expect_identical(core_xpath_text(result$document, "//mco:reference//cit:title/*"), "Provider terms")
    expect_true("Ask provider." %in% core_xpath_text(result$document, "//mco:otherConstraints/*"))
  }
})

test_that("missing release detail remains a validation failure and unknown codes are actionable", {
  core_validation_engine()
  fixture <- iso_export_candidate_pond("vector")
  on.exit(unlink(fixture$path, recursive = TRUE), add = TRUE)
  datapond:::save_dataset_release_rights(fixture$dataset_id,
    list(embargo_status = "No", dissemination_constraint_code = "approvedRecipients"), fixture$path)
  result <- datapond:::assess_iso_metadata_export(fixture$dataset_id, fixture$path, sections = "distribution")
  expect_identical(result$validation$status, "fail")
  expect_true(any(result$validation$issues$rule == "$hasAddresseeOrStatement"))
  conn <- datapond:::get_conn(fixture$path)
  on.exit(DBI::dbDisconnect(conn), add = TRUE)
  DBI::dbExecute(conn, "UPDATE dataset_license_tbl SET access_level_code = 'typo'")
  result <- datapond:::assess_iso_metadata_export(fixture$dataset_id, fixture$path, sections = "distribution")
  expect_identical(result$validation$status, "not-built")
  expect_match(result$validation$issues$message, "access-level")
})

