test_that("restoring a pre-edition snapshot keeps identity without inventing public provenance", {
  f <- release_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  legacy <- release_freeze(f)
  set_dataset_edition(f$id, f$pond, f$user, "in_house")
  restore_dataset_release(legacy$release_id, f$pond, f$user, "Restore the legacy baseline")
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  expect_identical(edition_row(conn, f$id)$edition, "in_house")
  snapshot <- release_read_payload(verify_dataset_release(legacy$release_id, f$pond)$snapshot)
  # Exercise an existing public record whose oldest snapshot predates its link.
  DBI::dbExecute(conn, "UPDATE dataset_edition_tbl SET edition='public',source_release_id='later-source',source_dataset_uuid='internal-source',source_version='2.0.0'")
  restored <- edition_restore_snapshot(conn, snapshot, f$id)
  expect_identical(restored$scoped$dataset_edition_tbl$edition, "public")
  expect_true(is.na(restored$scoped$dataset_edition_tbl$source_release_id))
  expect_error(edition_validate(restored), "Link this public draft")
  restored$scoped$dataset_edition_tbl$edition <- "in_house"
  expect_error(edition_restore_snapshot(conn, restored, f$id), "edition identity")
})
