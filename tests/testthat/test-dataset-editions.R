test_that("text projection preserves identifiers and GeoPackage projection removes unselected layers", {
  root <- tempfile(); dir.create(root); on.exit(unlink(root, recursive = TRUE), add = TRUE)
  csv <- file.path(root, "source.csv")
  writeLines(c('id,code,secret', '001,NA,private', '002,,private'), csv)
  target <- file.path(root, "public.csv")
  edition_project_file(csv, target, list(table = c("id", "code")))
  data <- edition_read_table(target)
  expect_identical(data$id, c("001", "002")); expect_identical(data$code, c("NA", ""))
  vector <- file.path(root, "source.gpkg")
  points <- sf::st_as_sf(data.frame(id = 1:2, secret = c("a", "b"), x = 1:2, y = 3:4), coords = c("x", "y"), crs = 4326)
  sf::st_write(points, vector, layer = "observations", quiet = TRUE)
  sf::st_write(points, vector, layer = "internal", quiet = TRUE)
  projected <- file.path(root, "public.gpkg")
  edition_project_file(vector, projected, list(observations = "id"))
  expect_identical(sf::st_layers(projected)$name, "observations")
  data <- sf::st_read(projected, quiet = TRUE)
  expect_false("secret" %in% names(data)); expect_equal(data$id, 1:2)
  expect_equal(sf::st_coordinates(data), sf::st_coordinates(points))
  expect_true(sf::st_crs(data) == sf::st_crs(points))
})

test_that("public freeze preserves provenance and separates local audit from transport", {
  f <- edition_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  # An existing, fully described record can be linked as the public edition.
  public <- release_fixture(); on.exit(unlink(public$root, recursive = TRUE), add = TRUE)
  # Use an ordinary transfer to create that distinct record in the source pond.
  conn <- get_conn(public$pond)
  old_folder <- public$folder
  public$folder <- file.path(public$pond, "dev", "public_example__public-fixture-uuid")
  stopifnot(file.rename(old_folder, public$folder))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET dataset_path=?,data_path=?", params=list(public$folder,file.path(public$folder,"data")))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET uuid='public-fixture-uuid',metadata_uuid='public-metadata-fixture',title='Public example'")
  write_dataset_marker(public$folder, "public-fixture-uuid", ensure_data_pond_id(public$pond, conn = conn))
  DBI::dbDisconnect(conn)
  bundle <- create_dataset_transfer_bundle(public$id, public$pond, public$user)
  imported <- import_dataset_transfer_bundle(bundle$path, f$pond, f$user)
  p <- list(root = f$root, pond = f$pond, id = imported$dataset_id, user = f$user, folder = imported$dataset_path)
  set_dataset_edition(p$id, p$pond, p$user, "public", f$release$release_id, "Public derivative, separately reviewed.")
  release_approve(p); release_prepare(p)
  frozen <- release_freeze(p)
  out <- file.path(f$root, "public-extract")
  paths <- verify_dataset_release(frozen$release_id, f$pond, out)
  private <- release_read_payload(paths$snapshot)
  expect_gt(nrow(private$scoped$metadata_review_tbl), 0)
  transfer <- release_read_payload(file.path(out, ".datapond_transfer", "dataset_metadata.sqlite"))
  expect_null(transfer$scoped$metadata_review_tbl)
  expect_null(transfer$scoped$dataset_import_tbl)
  expect_equal(nrow(transfer$user_tbl), 0)
  expect_identical(transfer$scoped$dataset_edition_tbl$source_release_id, f$release$release_id)
  before <- release_sha(paths$zip)
  record_dataset_publication(frozen$release_id, f$pond, f$user, "published", "Public portal", "Distributed after separate approval")
  family <- dataset_edition_family(f$id, f$pond)
  expect_identical(family$published_version[family$edition == "public"], "1.0.0")
  expect_identical(release_sha(paths$zip), before)
  expect_silent(preview_dataset_release(p$id, p$pond, p$user))
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  expect_error(edition_protect_release(conn, frozen$release_id), "currently published")
  # New internal and public versions are independent of the publication pointer.
  DBI::dbExecute(conn, "UPDATE entry_tbl SET version='2.0.0' WHERE id=?", params = list(f$id))
  release_approve(f); release_prepare(f)
  next_source <- release_freeze(f)
  DBI::dbExecute(conn, "UPDATE entry_tbl SET version='1.1.0' WHERE id=?", params = list(p$id))
  set_dataset_edition(p$id, p$pond, p$user, "public", next_source$release_id, "Updated public preparation")
  release_approve(p); release_prepare(p)
  next_public <- release_freeze(p)
  family <- dataset_edition_family(f$id, f$pond)
  expect_identical(family$latest_frozen[family$edition == "in_house"], "2.0.0")
  expect_identical(family$latest_frozen[family$edition == "public"], "1.1.0")
  expect_identical(family$published_version[family$edition == "public"], "1.0.0")
  expect_error(preview_dataset_release_removal(frozen$release_id, f$pond, f$user), "currently published")
  restore_dataset_release(frozen$release_id, f$pond, f$user, "Resume the earlier public baseline")
  expect_identical(edition_row(conn, p$id)$source_release_id, f$release$release_id)
  expect_identical(edition_current_publication(conn, p$id)$release_id, frozen$release_id)
  expect_silent(verify_dataset_release(next_public$release_id, f$pond))
  overview <- pond_overview_release_metadata(conn, data.frame(id = c(f$id, p$id)))
  expect_identical(overview$dataset_edition, c("in_house", "public"))
  expect_identical(overview$published_version, c(NA_character_, "1.0.0"))
  record_dataset_publication(frozen$release_id, f$pond, f$user, "withdrawn", "Public portal", "Withdrawn by publisher")
  expect_equal(nrow(edition_current_publication(conn, p$id)), 0)
  target <- release_fixture(); on.exit(unlink(target$root, recursive = TRUE), add = TRUE)
  imported_public <- import_dataset_transfer_bundle(paths$zip, target$pond, target$user)
  conn2 <- get_conn(target$pond); on.exit(DBI::dbDisconnect(conn2), add = TRUE)
  imported_edition <- edition_row(conn2, imported_public$dataset_id)
  expect_identical(imported_edition$source_release_id, f$release$release_id)
  expect_identical(imported_edition$family_uuid, f$release$dataset_uuid)
  expect_equal(nrow(edition_current_publication(conn2, imported_public$dataset_id)), 0L)
})

test_that("public draft journals reconcile both sides of a process interruption", {
  f <- edition_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  draft <- create_public_dataset_draft(f$release$release_id, f$pond, f$user, "Public", "1.0.0",
    "data/measurements.csv", preparation_method = "Selected file")
  journal <- file.path(f$pond, ".metadata_pond", "edition-drafts", draft$dataset_uuid, "edition-operation.json")
  op <- jsonlite::read_json(journal); op$phase <- "prepared"; release_operation_write(op, journal)
  expect_error(release_lock(f$pond, f$id), "public draft operation needs recovery")
  expect_match(recover_dataset_release_operations(f$id, f$pond, f$user), "Public draft: complete")
  expect_true(dir.exists(draft$dataset_path))
  # Simulate filesystem placement followed by SQLite rollback/process death.
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  DBI::dbWithTransaction(conn, {
    DBI::dbExecute(conn, "PRAGMA defer_foreign_keys=ON")
    for (table in DBI::dbGetQuery(conn, "SELECT name FROM sqlite_master WHERE type='table'")$name) if ("dataset_id" %in% DBI::dbListFields(conn, table))
      DBI::dbExecute(conn, paste0("DELETE FROM ", DBI::dbQuoteIdentifier(conn, table), " WHERE dataset_id=?"), params = list(draft$dataset_id))
    DBI::dbExecute(conn, "DELETE FROM entry_tbl WHERE id=?", params = list(draft$dataset_id))
  })
  op$phase <- "prepared"; release_operation_write(op, journal)
  expect_match(recover_dataset_release_operations(f$id, f$pond, f$user), "Public draft: rolled_back")
  expect_false(dir.exists(draft$dataset_path))
  expect_true(file.exists(file.path(op$directory, "unregistered-draft", "data", "measurements.csv")))
})

