test_that("document collection is read-only and preserves lineage authority", {
  f <- iso_export_candidate_pond("vector")
  on.exit(unlink(f$path, recursive = TRUE), add = TRUE)
  root <- iso_package_fixture_files(f)
  writeLines(c("---", "title: Development", "---", "```{r}", "stop('MUST NOT RUN')", "```"),
    file.path(root, "data_dev_example.qmd"))
  writeLines("Legacy development report", file.path(root, "data_dev_legacy.Rmd"))
  writeLines("Supplementary processing", file.path(root, "processing.qmd"))
  dir.create(file.path(root, "arc"))
  writeLines("Archived", file.path(root, "arc", "data_dev_old.qmd"))
  conn <- datapond:::get_conn(f$path)
  datapond:::ensure_columns(conn, "entry_tbl", c("citation", "access_constraints", "use_limitations"))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET citation='Example Office (2026). Sample dataset (Version 1.2).',
    access_constraints='Contact the custodian.', use_limitations='Regional use only.'")
  DBI::dbExecute(conn, "UPDATE dataset_lineage_tbl SET lineage_notes='PRIVATE CURATOR NOTE', processing_tools='PRIVATE TOOL INVENTORY'")
  DBI::dbExecute(conn, "INSERT INTO supporting_document_tbl
    (dataset_id, document_rel_path, document_name, active, include_in_lineage, include_in_metadata)
    VALUES (1, 'data_dev_example.qmd', 'Development report', 1, 0, 1)")
  DBI::dbDisconnect(conn)
  before <- tools::md5sum(file.path(f$path, "metadata.db"))
  s <- datapond:::collect_metadata_document(1, f$path)
  body <- paste(datapond:::metadata_document_body(s), collapse = "\n")
  expect_identical(unname(tools::md5sum(file.path(f$path, "metadata.db"))), unname(before))
  expect_setequal(s$development_documents, c("data_dev_example.qmd", "data_dev_legacy.Rmd", "processing.qmd"))
  expect_identical(s$documents$include_in_lineage[s$documents$document_name == "Development report"], 0L)
  expect_match(body, "Recorded lineage references", fixed = TRUE)
  expect_match(body, "Software|software")
  expect_false(grepl("PRIVATE|MUST NOT RUN|data_dev_old|/home/|file:///", body))
  expect_match(body, "Regional use only", fixed = TRUE)
  expect_match(body, "Not recorded", fixed = TRUE)
  output <- tempfile(); dir.create(output)
  on.exit(unlink(output, recursive = TRUE), add = TRUE)
  datapond:::write_metadata_document_source(s, output)
  expect_identical(readLines(file.path(output, "citation.txt")), s$record$citation)
  expect_true(file.exists(file.path(output, "ekznw-theme", "pdf-header.tex")))
  expect_true(file.exists(file.path(output, "ekznw-theme", "style", "img", "corplogo120.png")))
  qmd <- paste(readLines(file.path(output, "metadata.qmd")), collapse = "\n")
  expect_match(qmd, "enabled: false", fixed = TRUE)
  expect_false(grepl(f$path, qmd, fixed = TRUE))
})

test_that("inactive and foreign file attributes do not leak into the dictionary", {
  f <- iso_export_candidate_pond("vector")
  on.exit(unlink(f$path, recursive = TRUE), add = TRUE)
  conn <- datapond:::get_conn(f$path)
  DBI::dbExecute(conn, "UPDATE data_file_tbl SET active=0")
  DBI::dbDisconnect(conn)
  s <- datapond:::collect_metadata_document(1, f$path)
  expect_equal(nrow(s$files), 0)
  expect_equal(nrow(s$attributes), 0)
  expect_equal(s$unlinked_attribute_count, 1)
  body <- paste(datapond:::metadata_document_body(s), collapse = "\n")
  expect_false(grepl("Documented fixture measurement", body, fixed = TRUE))
})

test_that("text and paths cannot introduce executable document markup", {
  value <- '\\input{/tmp/secret} {{< include /tmp/secret >}} <script>bad()</script> `r stop("bad")`'
  escaped <- datapond:::metadata_markdown(value)
  expect_false(grepl("{{<", escaped, fixed = TRUE))
  expect_true(startsWith(escaped, "\\\\input\\{"))
  expect_identical(datapond:::metadata_public_path("../secret.txt"),
    "Local reference omitted; record a dataset-relative path")
  expect_identical(datapond:::metadata_public_path("C:\\private\\file.txt"),
    "Local reference omitted; record a dataset-relative path")
  expect_identical(datapond:::metadata_public_path("data_dev_example.qmd"), "data_dev_example.qmd")
  expect_identical(datapond:::metadata_public_path("https://example.test/methods"), "https://example.test/methods")
})

test_that("metadata export preserves existing folders and rejects pond destinations", {
  f <- iso_export_candidate_pond("tabular")
  on.exit(unlink(f$path, recursive = TRUE), add = TRUE)
  parent <- tempfile(); dir.create(parent)
  on.exit(unlink(parent, recursive = TRUE), add = TRUE)
  existing <- file.path(parent, "existing"); dir.create(existing)
  writeLines("keep", file.path(existing, "metadata.pdf"))
  expect_error(datapond::write_metadata_pdf(1, f$path, existing), "never overwritten")
  expect_identical(readLines(file.path(existing, "metadata.pdf")), "keep")
  expect_error(datapond::write_metadata_pdf(1, f$path, file.path(f$path, "export")), "outside the Data Pond")
  testthat::local_mocked_bindings(render_metadata_document = function(directory) stop("Renderer unavailable"), .package = "datapond")
  expect_error(datapond::write_metadata_pdf(1, f$path, file.path(parent, "failed")), "Renderer unavailable")
  expect_false(dir.exists(file.path(parent, "failed")))
  expect_length(list.files(parent, pattern = "metadata-stage", all.files = TRUE), 0)
})
