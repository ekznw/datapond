data_dev_fixture <- function() {
  pond <- tempfile("data-dev-pond-")
  dir.create(pond)
  datapond:::ensure_pond_structure(pond)
  datapond:::init_db(pond)
  folder <- file.path(pond, "dev", "template-example")
  dir.create(folder)
  conn <- datapond:::get_conn(pond)
  on.exit(DBI::dbDisconnect(conn))
  DBI::dbExecute(conn, "INSERT INTO persons_tbl(id,name_first,name_last) VALUES (1,'Template','Tester')")
  DBI::dbExecute(conn, "INSERT INTO user_tbl(id,person_id,user_name,is_active) VALUES (1,1,'template-tester',1)")
  DBI::dbExecute(conn, "INSERT INTO entry_tbl(id,title,dataset_path,lifecycle_status,folder_locked)
    VALUES (1,'Template example',?,'draft',0)", params = list(folder))
  list(pond = pond, folder = folder)
}

test_that("Word is copied byte-for-byte and registered without asserting lineage authority", {
  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  path <- datapond:::add_dataset_data_dev_template(1, f$pond, 1, "docx", "pisr")
  expect_identical(path, file.path(f$folder, "data_dev_pisr.docx"))
  expect_identical(unname(tools::md5sum(path)),
    unname(tools::md5sum(datapond:::datapond_resource("data_dev_template", "data_dev.docx"))))
  docs <- datapond:::get_supporting_documents(1, f$pond)
  expect_equal(nrow(docs), 1)
  expect_identical(docs$document_rel_path, "data_dev_pisr.docx")
  expect_identical(docs$include_in_lineage, 0L)
  expect_true(is.na(docs$reviewed_at))
  expect_null(datapond:::get_dataset_lineage(1, f$pond))
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1, "docx", "pisr"), "nothing was replaced")
  # Ordinary later scans must retain the explicit non-authoritative flag.
  datapond:::scan_supporting_documents(1, f$folder, f$pond)
  expect_identical(datapond:::get_supporting_documents(1, f$pond)$include_in_lineage, 0L)
})

test_that("Quarto has isolated portable styles and does not alter existing files", {
  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  dir.create(file.path(f$folder, "ekznw-theme"))
  writeLines("Keep metadata styling", file.path(f$folder, "ekznw-theme", "ekznw.yml"))
  path <- datapond:::add_dataset_data_dev_template(1, f$pond, 1, "qmd", "pu")
  qmd <- paste(readLines(path), collapse = "\n")
  expect_match(qmd, "data_dev_pu_theme/word-guidance.lua", fixed = TRUE)
  expect_match(qmd, "enabled: false", fixed = TRUE)
  expect_false(grepl("ekznw-theme/", qmd, fixed = TRUE))
  theme <- file.path(f$folder, "data_dev_pu_theme")
  expect_true(all(file.exists(file.path(theme, c("ekznw.yml", "pdf-header.tex", "reference.docx", "word-guidance.lua", "style/img/corplogo120.png")))))
  expect_match(paste(readLines(file.path(theme, "ekznw.yml")), collapse = "\n"), "data_dev_pu_theme/pdf-header.tex", fixed = TRUE)
  expect_match(paste(readLines(file.path(theme, "pdf-header.tex")), collapse = "\n"), "data_dev_pu_theme/style/img/", fixed = TRUE)
  expect_identical(readLines(file.path(f$folder, "ekznw-theme", "ekznw.yml")), "Keep metadata styling")
  expect_equal(nrow(datapond:::get_supporting_documents(1, f$pond)), 1)
  datapond:::scan_supporting_documents(1, f$folder, f$pond)
  expect_identical(datapond:::get_supporting_documents(1, f$pond)$document_rel_path, "data_dev_pu.qmd")
  expect_identical(datapond:::get_supporting_documents(1, f$pond)$include_in_lineage, 0L)
  dir.create(file.path(f$folder, "data_dev_other_theme"))
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1, "qmd", "other"), "nothing was replaced")
  expect_false(file.exists(file.path(f$folder, "data_dev_other.qmd")))
})

test_that("lifecycle and user guards reject writes and filename traversal", {
  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  expect_error(datapond:::add_dataset_data_dev_template(NULL, f$pond, 1), "Select and save")
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, NA_integer_), "active application user")
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1, "pdf"), "Word or Quarto")
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1, "qmd", "../outside"), "letters, numbers")
  conn <- datapond:::get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  DBI::dbExecute(conn, "UPDATE entry_tbl SET folder_locked=1")
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1), "Unlock")
  DBI::dbExecute(conn, "UPDATE entry_tbl SET folder_locked=0, lifecycle_status='archived'")
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1), "Restore")
  DBI::dbExecute(conn, "UPDATE entry_tbl SET lifecycle_status='draft',dataset_path=?", params = list(file.path(f$pond, "arc")))
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1), "editable dataset")
  expect_length(list.files(f$folder, all.files = TRUE, no.. = TRUE), 0)
  expect_equal(nrow(datapond:::get_supporting_documents(1, f$pond)), 0)
})

test_that("registration failures remove only the newly created files", {
  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  writeLines("Existing methods", file.path(f$folder, "data_dev_existing.qmd"))
  conn <- datapond:::get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
