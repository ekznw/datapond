  DBI::dbExecute(conn, "UPDATE entry_tbl SET folder_locked=0")
  expect_error(datapond:::preview_data_dev_sync(1, f$pond, NA_integer_, basename(path)), "active application user")
  form <- list(title = "Unsaved edit")
  p <- datapond:::preview_data_dev_sync(1, f$pond, 1, basename(path), "import", form = form)
  expect_identical(p$changes$Current, "Unsaved edit")
  expect_error(datapond:::apply_data_dev_sync(p, 1, list(title = "Another edit")), "form changed")
  expect_identical(datapond:::apply_data_dev_sync(p, 1, form)$values$title, "Template example")
  expect_identical(DBI::dbGetQuery(conn, "SELECT title FROM entry_tbl")$title, "Updated title")
  expect_error(datapond:::preview_data_dev_sync(1, f$pond, 1, basename(path), "import", fields = "uuid"), "UUID cannot be imported")
  staged <- tempfile(fileext = ".qmd"); on.exit(unlink(staged), add = TRUE)
