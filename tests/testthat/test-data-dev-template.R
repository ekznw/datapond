  expect_identical(readLines(file.path(f$folder, "data_dev_existing.qmd")), "Existing methods")
})

test_that("broken links, active reviews and lifecycle operations cannot be overwritten", {
  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  target <- file.path(f$folder, "data_dev.docx")
  if (.Platform$OS.type == "unix") {
    expect_true(file.symlink(file.path(f$pond, "absent"), target))
    expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1), "nothing was replaced")
    expect_identical(Sys.readlink(target), file.path(f$pond, "absent"))
    unlink(target)
  }
  lock <- datapond:::release_lock(f$pond, 1)
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1), "lifecycle operation")
  unlink(lock, recursive = TRUE)
  conn <- datapond:::get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  datapond:::review_ensure_schema(conn)
  DBI::dbExecute(conn, "INSERT INTO dataset_review_exchange_tbl
    (review_id,dataset_id,role,status,master_pond_id,dataset_uuid,request_bundle_id,baseline_hash,files_hash,assignee,issued_at)
    VALUES ('test-review',1,'master','issued','pond','uuid','bundle','hash','hash','tester','2026-10-21')")
  expect_error(datapond:::add_dataset_data_dev_template(1, f$pond, 1), "active metadata review")
  expect_false(file.exists(target))
})

test_that("the Lineage action adds a template and refreshes supporting documents", {
  local_trusted_access_fixture()

  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  state <- shiny::reactiveValues(current_dataset_id = 1L, data_pond = f$pond,
    active_user_id = 1L, refresh_supporting_docs = 0L)
  shiny::testServer(datapond:::mod_data_dev_template_server, args = list(state = state), {
    session$setInputs(format = "docx", project = "team", add = 1)
    expect_true(file.exists(file.path(f$folder, "data_dev_team.docx")))
    expect_equal(state$refresh_supporting_docs, 1L)
    expect_match(output$result, "Created:", fixed = TRUE)
    session$setInputs(add = 2)
    expect_equal(state$refresh_supporting_docs, 1L)
    expect_equal(nrow(datapond:::get_supporting_documents(1, f$pond)), 1)
  })
  html <- as.character(datapond:::mod_lineage_ui("lineage"))
  expect_match(html, "Add data development template", fixed = TRUE)
  expect_match(html, 'lineage-data_dev_template-add', fixed = TRUE)
})
