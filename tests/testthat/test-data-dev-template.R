test_that("metadata sync round-trips both report formats without changing methods or report versions", {
  f <- data_dev_fixture(); on.exit(unlink(f$pond, recursive = TRUE), add = TRUE)
  conn <- datapond:::get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  datapond:::ensure_columns(conn, "entry_tbl", c("purpose", "uuid"))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET title=?,version='2.3.4',abstract=?,purpose=?,uuid='dataset-one'",
    params = list('River "A" & wetlands', "First line\nSecond line — café", "Conservation <planning>"))
  for (format in c("qmd", "docx")) {
    path <- datapond:::add_dataset_data_dev_template(1, f$pond, 1, format)
    before <- readBin(path, "raw", n = file.info(path)$size)
    preview <- datapond:::preview_data_dev_sync(1, f$pond, 1, basename(path))
    expect_equal(nrow(preview$changes), 4L)
    result <- datapond:::apply_data_dev_sync(preview, 1)
    expect_identical(readBin(result$backup, "raw", n = file.info(result$backup)$size), before)
    report <- datapond:::data_dev_sync_document(path)
    expect_identical(report$title, 'River "A" & wetlands')
    expect_identical(report$version, "2.3.4")
    expect_identical(report$abstract, "First line\nSecond line — café")
    expect_identical(report$purpose, "Conservation <planning>")
    imported <- datapond:::preview_data_dev_sync(1, f$pond, 1, basename(path), "import")
    expect_identical(datapond:::apply_data_dev_sync(imported, 1)$values, report[c("title", "version", "abstract", "purpose")])
    # A second export is repeatable and cannot duplicate the metadata section.
    again <- datapond:::preview_data_dev_sync(1, f$pond, 1, basename(path))
    datapond:::apply_data_dev_sync(again, 1)
    expect_identical(datapond:::data_dev_sync_document(path), report)
    if (format == "qmd") {
      lines <- readLines(path)
      expect_equal(sum(lines == "<!-- datapond-metadata:start -->"), 1)
      expect_true("**Report version and date:** [report version] / [YYYY-MM-DD]" %in% lines)
      expect_true("# Data processing" %in% lines)
    } else {
      original <- datapond:::datapond_resource("data_dev_template", "data_dev.docx")
      a <- tempfile(); b <- tempfile(); dir.create(a); dir.create(b)
      on.exit(unlink(c(a, b), recursive = TRUE), add = TRUE)
      utils::unzip(original, exdir = a); utils::unzip(path, exdir = b)
      members <- setdiff(list.files(a, recursive = TRUE, all.files = TRUE), "word/document.xml")
      expect_identical(unname(tools::md5sum(file.path(a, members))), unname(tools::md5sum(file.path(b, members))))
      doc <- xml2::read_xml(file.path(b, "word/document.xml"))
      text <- xml2::xml_text(doc)
      expect_match(text, "Report version and date: [report version] / [YYYY-MM-DD]", fixed = TRUE)
      expect_match(text, "Data processing", fixed = TRUE)
    }
  }
})

