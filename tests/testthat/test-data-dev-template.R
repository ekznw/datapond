  write("\nA new methods paragraph.", path, append = TRUE)
  expect_error(datapond:::apply_data_dev_sync(p, 1), "changed since preview")
  p <- datapond:::preview_data_dev_sync(1, f$pond, 1, basename(path))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET title='Updated title'")
  expect_error(datapond:::apply_data_dev_sync(p, 1), "changed since preview")
  expect_error(datapond:::preview_data_dev_sync(1, f$pond, 1, "../data_dev.qmd"), "Choose a data_dev")
