})

test_that("selected vector layers produce public bounds and omit other layers", {
  f <- release_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  gpkg <- file.path(f$folder, "data", "places.gpkg")
  public_points <- sf::st_as_sf(data.frame(id = 1:2, secret = c("a", "b"), x = c(29, 30), y = c(-28, -27)), coords = c("x", "y"), crs = 4326)
  private_points <- sf::st_as_sf(data.frame(id = 3, x = 10, y = 10), coords = c("x", "y"), crs = 4326)
  sf::st_write(public_points, gpkg, layer = "observations", quiet = TRUE)
  sf::st_write(private_points, gpkg, layer = "private", quiet = TRUE)
  set_dataset_edition(f$id, f$pond, f$user, "in_house"); release_approve(f); release_prepare(f); r <- release_freeze(f)
  p <- create_public_dataset_draft(r$release_id, f$pond, f$user, "Public places", "1.0.0", "data/places.gpkg",
    list("data/places.gpkg" = list(observations = "id")), "Selected public observations")
  expect_identical(sf::st_layers(file.path(p$dataset_path, "data", "places.gpkg"))$name, "observations")
  spatial <- get_saved_data_file_spatial_metadata(p$dataset_id, f$pond)
  expect_equal(nrow(spatial), 1L)
  expect_equal(spatial$xmin, 29); expect_equal(spatial$xmax, 30)
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  attrs <- transfer_table_rows(conn, "dataset_attribute_tbl", p$dataset_id)
  expect_identical(attrs$data_field_name, "id")
})
