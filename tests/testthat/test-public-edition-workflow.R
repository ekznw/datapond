public_workflow_fixture <- function() {
  f <- release_fixture()
  set_dataset_edition(f$id, f$pond, f$user, "in_house")
  release_approve(f); release_prepare(f); f$release <- release_freeze(f)
  f$public <- create_public_dataset_draft(f$release$release_id, f$pond, f$user, "Public observations", "1.0.0",
    "data/measurements.csv", list("data/measurements.csv" = list(table = "value")), "Retain public values")
  f
}
public_next_source <- function(f) {
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn))
  DBI::dbExecute(conn, "UPDATE entry_tbl SET version='2.0.0',abstract='New source abstract',purpose='New source purpose' WHERE id=?", params = list(f$id))
  writeLines(c("id,value,private_new", "1,40,secret"), file.path(f$folder, "data", "measurements.csv"))
  release_approve(f); release_prepare(f); release_freeze(f)
}

test_that("defaults copy only selected definitions, retain constraints, nominate contacts and keep private baselines private", {
  f <- release_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  DBI::dbExecute(conn, "UPDATE persons_tbl SET organisation_id=1 WHERE id=1")
  set_public_metadata_defaults(f$id, f$pond, f$user, "entry:abstract", organisation_id = 1L, person_id = 1L)
  expect_error(set_public_metadata_defaults(f$id, f$pond, f$user, "table:dataset_license_tbl"), "restrictions")
  set_dataset_edition(f$id, f$pond, f$user, "in_house"); release_approve(f); release_prepare(f); r <- release_freeze(f)
  ch <- public_edition_choices(r$release_id, f$pond)
  expect_identical(ch$selected_files, "data/measurements.csv")
  p <- create_public_dataset_draft(r$release_id, f$pond, f$user, "Public", "1.0.0", ch$selected_files,
    list("data/measurements.csv" = list(table = "value")), "Selected values")
  entry <- release_entry(conn, p$dataset_id)
  expect_true(is.na(entry$abstract)); expect_identical(entry$purpose, "Test frozen versions.")
  expect_match(entry$citation, "Public")
  expect_identical(entry$access_constraints, "Internal")
  attrs <- transfer_table_rows(conn, "dataset_attribute_tbl", p$dataset_id)
  expect_identical(attrs$data_field_name, "value"); expect_identical(attrs$data_field_desc, "Measured value")
  expect_equal(transfer_table_rows(conn, "poc_tbl", p$dataset_id)$person_id, 1L)
  expect_equal(nrow(transfer_table_rows(conn, "metadata_review_tbl", p$dataset_id)), 0L)
  payload <- release_payload(conn, p$dataset_id, f$pond, f$user)
  expect_true("dataset_public_derivation_tbl" %in% names(payload$scoped))
  public <- edition_transfer_payload(payload)
  expect_false(any(c("dataset_public_derivation_tbl", "dataset_public_metadata_policy_tbl") %in% names(public$scoped)))
})

test_that("updates reuse selections, merge source changes, preserve public edits and roll back without a public freeze", {
  f <- public_workflow_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  conn <- get_conn(f$pond); on.exit(DBI::dbDisconnect(conn), add = TRUE)
  id <- f$public$dataset_id
  DBI::dbExecute(conn, "UPDATE entry_tbl SET abstract='Public explanation' WHERE id=?", params = list(id))
  writeLines("Public user manual", file.path(f$public$dataset_path, "public-guide.md"))
  next_source <- public_next_source(f)
  ch <- public_edition_choices(next_source$release_id, f$pond, id)
  expect_identical(ch$selected_fields[[1]]$table, "value")
  expect_true(any(grepl("private_new", ch$changes)))
  plan <- preview_public_dataset_draft(next_source$release_id, f$pond, f$user, ch$selected_files, ch$selected_fields, id)
  expect_identical(names(plan$conflicts), "entry:abstract")
  expect_identical(public_decode(plan$metadata[["entry:title"]]), "Public observations")
  expect_identical(public_decode(plan$metadata[["entry:purpose"]]), "New source purpose")
  expect_error(apply_public_dataset_draft(plan, "Public observations", "1.0.1", "New source"), "Resolve")
  updated <- apply_public_dataset_draft(plan, "Public observations", "1.0.1", "New source", list("entry:abstract" = "current"))
  expect_identical(updated$dataset_id, id); expect_identical(updated$dataset_uuid, f$public$dataset_uuid)
  entry <- release_entry(conn, id)
  expect_identical(entry$abstract, "Public explanation"); expect_identical(entry$purpose, "New source purpose")
  expect_identical(names(read.csv(file.path(entry$dataset_path, "data", "measurements.csv"))), "value")
  expect_equal(read.csv(file.path(entry$dataset_path, "data", "measurements.csv"))$value, 40)
  expect_identical(readLines(file.path(entry$dataset_path, "public-guide.md")), "Public user manual")
  expect_equal(nrow(dataset_release_checkpoints(id, f$pond)), 1L)
  restored <- restore_dataset_checkpoint(updated$checkpoint, f$pond, f$user, "Undo update")
  expect_identical(restored$dataset_id, id)
  expect_identical(release_entry(conn, id)$purpose, "Test frozen versions.")
  expect_equal(read.csv(file.path(restored$dataset_path, "data", "measurements.csv"))$value, 20)
  expect_identical(edition_row(conn, id)$source_release_id, f$release$release_id)
  expect_silent(verify_dataset_release(next_source$release_id, f$pond))
})

test_that("edited public files need an explicit choice and stale previews are rejected", {
  f <- public_workflow_fixture(); on.exit(unlink(f$root, recursive = TRUE), add = TRUE)
  id <- f$public$dataset_id
  writeLines(c('"value"', '"99"'), file.path(f$public$dataset_path, "data", "measurements.csv"))
  next_source <- public_next_source(f)
  ch <- public_edition_choices(next_source$release_id, f$pond, id)
  p <- preview_public_dataset_draft(next_source$release_id, f$pond, f$user, ch$selected_files, ch$selected_fields, id)
  on.exit(unlink(p$stage, recursive = TRUE), add = TRUE)
  expect_true("file:data/measurements.csv" %in% names(p$conflicts))
  writeLines("New edit after preview", file.path(f$public$dataset_path, "manual.md"))
  expect_error(apply_public_dataset_draft(p, "Public", "1.0.1", "Refresh", list("file:data/measurements.csv" = "current")), "changed after preview")
  q <- preview_public_dataset_draft(next_source$release_id, f$pond, f$user, ch$selected_files, ch$selected_fields, id)
  updated <- apply_public_dataset_draft(q, "Public", "1.0.1", "Retain edited public data", list("file:data/measurements.csv" = "current"))
  expect_equal(read.csv(file.path(updated$dataset_path, "data", "measurements.csv"))$value, 99)
})

